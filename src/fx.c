fx_ang fx_atan2(fx y, fx x)
{
    if (!x && !y) return 0;
    uint32_t ax = x < 0 ? 0u - (uint32_t)x : (uint32_t)x, ay = y < 0 ? 0u - (uint32_t)y : (uint32_t)y;
    bool swap = ay > ax;
    uint32_t lo = swap ? ax : ay, hi = swap ? ay : ax;
    if (hi & 0x80000000u) { hi >>= 1; lo >>= 1; }   /* the divider's operands are signed */
    /* t = lo / hi in 0.16, rounded, then the table in 1/256 steps with 8 bits of interpolation */
    uint32_t t = (uint32_t)div64_32(((int64_t)lo << 16) + (hi >> 1), (int32_t)hi);
    if (t > 0x10000) t = 0x10000;
    uint32_t k = t >> 8, f = t & 0xFF;
    int32_t v = k >= 256 ? ATAN_T[256] : ATAN_T[k] + (((ATAN_T[k + 1] - ATAN_T[k]) * (int32_t)f + 128) >> 8);
    if (swap) v = 16384 - v;        /* the octants past 45 degrees */
    if (x < 0) v = 32768 - v;       /* the left half */
    if (y < 0) v = -v;              /* below the x axis */
    return (fx_ang)(int16_t)v;
}
