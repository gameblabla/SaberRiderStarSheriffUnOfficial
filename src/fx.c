fx fx_sin(fx_ang a)
{
    uint32_t u = (uint32_t)a & 0xFFFF, q = u >> 14, i = u & 0x3FFF;
    if (q & 1) i = 0x4000 - i;   /* the falling quarters mirror the rising ones */
    uint32_t k = i >> 4, f = i & 15;
    fx v = k >= 1024 ? SIN_Q[1024] : SIN_Q[k] + (fx)(((SIN_Q[k + 1] - SIN_Q[k]) * (int32_t)f + 8) >> 4);
    return q & 2 ? -v : v;
}

